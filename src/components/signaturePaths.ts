/** 按实际弧长分配时间；抬笔留短暂停顿，不沿空白画线。 */
export function signatureFrame(lengths: readonly number[], progress: number) {
  const gap = 10;
  const total = lengths.reduce((sum, length) => sum + length + gap, 0) - gap;
  const distance = Math.max(0, Math.min(1, progress)) * Math.max(0, total);
  let start = 0;
  return lengths.map((length) => {
    const drawn = progress >= 1 ? length : Math.max(0, Math.min(length, distance - start));
    const active = distance >= start && distance < start + length;
    start += length + gap;
    return { drawn, active };
  });
}
